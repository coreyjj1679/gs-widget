pub(super) fn cumulative_experience(level: i64) -> Option<u64> {
    (1..=260)
        .contains(&level)
        .then(|| CUMULATIVE_EXPERIENCE[level as usize])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn client_normal_experience_curve_boundaries() {
        assert_eq!(cumulative_experience(1), Some(0));
        assert_eq!(cumulative_experience(100), Some(18_350_220));
        assert_eq!(cumulative_experience(200), Some(1_989_823_220));
        assert_eq!(cumulative_experience(249), Some(28_686_973_590));
        assert_eq!(cumulative_experience(250), Some(30_000_000_000));
        assert_eq!(cumulative_experience(251), Some(32_313_026_410));
        assert_eq!(cumulative_experience(260), Some(300_000_000_000));
        for level in 2..=260 {
            assert!(cumulative_experience(level) > cumulative_experience(level - 1));
        }
        assert_eq!(cumulative_experience(0), None);
        assert_eq!(cumulative_experience(261), None);
        assert_eq!(cumulative_experience(-1), None);
    }
}
