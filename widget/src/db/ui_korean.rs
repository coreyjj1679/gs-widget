#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::path::Path;

    #[derive(Debug, PartialEq)]
    enum Token {
        Identifier(String),
        Literal(String),
        Punctuation(u8),
    }

    // Read string literals rather than matching lines, so escaped quotes,
    // multiline calls, and examples inside comments cannot hide a missing key.
    fn tokens(source: &str) -> Vec<Token> {
        let bytes = source.as_bytes();
        let mut result = Vec::new();
        let mut at = 0;
        while at < bytes.len() {
            if source[at..].starts_with("//") {
                at += source[at..].find('\n').unwrap_or(bytes.len() - at);
            } else if source[at..].starts_with("/*") {
                at += 2;
                at += source[at..].find("*/").map_or(bytes.len() - at, |end| end + 2);
            } else if bytes[at] == b'"' {
                let start = at;
                at += 1;
                while at < bytes.len() {
                    if bytes[at] == b'\\' {
                        at += 2;
                    } else if bytes[at] == b'"' {
                        at += 1;
                        break;
                    } else {
                        at += 1;
                    }
                }
                let literal = serde_json::from_str(&source[start..at])
                    .expect("Slint UI translation literals must use JSON-compatible escapes");
                result.push(Token::Literal(literal));
            } else if bytes[at].is_ascii_alphabetic() || bytes[at] == b'_' {
                let start = at;
                at += 1;
                while at < bytes.len()
                    && (bytes[at].is_ascii_alphanumeric() || matches!(bytes[at], b'_' | b'-'))
                {
                    at += 1;
                }
                result.push(Token::Identifier(source[start..at].to_string()));
            } else {
                if !bytes[at].is_ascii_whitespace() {
                    result.push(Token::Punctuation(bytes[at]));
                }
                at += source[at..].chars().next().unwrap().len_utf8();
            }
        }
        result
    }

    fn literal_keys(source: &str) -> BTreeSet<String> {
        tokens(source)
            .windows(5)
            .filter_map(|window| match window {
                [Token::Identifier(global), Token::Punctuation(b'.'), Token::Identifier(function), Token::Punctuation(b'('), Token::Literal(key)]
                    if global == "UiLanguage" && function == "tr" => Some(key.clone()),
                _ => None,
            })
            .collect()
    }

    #[test]
    fn every_native_ui_literal_has_a_nonempty_korean_translation() {
        let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("ui");
        let mut checked = BTreeSet::new();
        let mut missing = Vec::new();
        for entry in std::fs::read_dir(directory).expect("native UI sources") {
            let path = entry.unwrap().path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("slint") {
                continue;
            }
            let source = std::fs::read_to_string(&path).unwrap();
            for key in literal_keys(&source) {
                if super::translated(&key).is_none_or(|text| text.trim().is_empty()) {
                    missing.push(format!("{}: {key:?}", path.display()));
                }
                checked.insert(key);
            }
        }
        assert!(!checked.is_empty(), "no UiLanguage.tr literals were checked");
        assert!(missing.is_empty(), "Missing Korean UI translations:\n{}", missing.join("\n"));
        // These first arguments are selected dynamically for English pluralization.
        for key in [" quest", " quests", " quest. ", " quests. ", " group", " groups"] {
            assert!(super::translated(key).is_some_and(|text| !text.trim().is_empty()), "{key:?}");
        }
    }

    #[test]
    fn ui_key_scan_handles_escapes_whitespace_and_comments() {
        let source = r#"
            // UiLanguage.tr("comment", "ignored")
            /* UiLanguage.tr("block comment", "ignored") */
            text: UiLanguage . tr (
                "Line\n\"quoted\"", "說明"
            );
            text: "UiLanguage.tr(\"inside a string\", \"ignored\")";
            text: UiLanguage.tr("Other", "其他");
        "#;
        assert_eq!(literal_keys(source), BTreeSet::from(["Line\n\"quoted\"".to_string(), "Other".to_string()]));
    }
}
